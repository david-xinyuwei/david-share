"""Build the generic sedan shell used by system scenes (vehicle_tms) as a translucent context model.

The shell is procedural (CadQuery / OCCT) and deliberately brand-neutral: a side-profile silhouette extruded
across the body width, rounded, with wheel arches, four wheels and a simple greenhouse. It replaces the earlier
third-party GLB (BMW styling) so the asset can go into customer-facing material without licence questions.

    python assets/build_car_shell.py            # writes static/assets/car/sedan.glb (+ SOURCE.txt)

Units: modelled in mm (1 CadQuery unit = 1 mm). OCCT's glTF writer converts to metres and Y-up, so the GLB is
~4.6 units long; scenes that use 1 unit = 1 mm scale the loaded shell by 1000 (see SOURCE.txt / scenarios.py).
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

import cadquery as cq

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "static" / "assets" / "car"

# Overall dimensions of a generic D-segment sedan (mm)
LENGTH, WIDTH, HEIGHT = 4600.0, 1850.0, 1450.0
WHEELBASE, TRACK = 2750.0, 1580.0
WHEEL_R, WHEEL_W, RIM_R = 340.0, 225.0, 240.0
FLOOR_Z = 330.0                          # underside of the body above ground (z = 0 is the road)
WHEEL_X = (WHEELBASE / 2, -WHEELBASE / 2)   # front (+X), rear (−X)


def side_profile() -> list[tuple[float, float]]:
    """Silhouette in the XZ plane (x forward, z up), closed clockwise from the rear lower corner."""
    return [
        (-2300, FLOOR_Z), (-2300, 800), (-2200, 990), (-1650, 1060),   # rear bumper → trunk lid
        (-1300, 1080), (-900, 1400), (-350, 1450), (450, 1440),        # rear window → roof
        (900, 1330), (1380, 1010), (1500, 985), (2150, 840),            # windshield → hood
        (2300, 770), (2300, FLOOR_Z),                                    # front bumper
    ]


def body() -> cq.Workplane:
    prof = cq.Workplane("XZ").polyline(side_profile()).close().extrude(WIDTH / 2, both=True)
    # Plan-view outline: rounded rectangle so the nose and tail corners are not slab-flat.
    plan = (cq.Workplane("XY").workplane(offset=FLOOR_Z - 50)
            .sketch().rect(LENGTH, WIDTH).vertices().fillet(420).finalize()
            .extrude(HEIGHT))
    shell = prof.intersect(plan)
    # Greenhouse taper: shave the roof sides with two angled cuts so the cabin is narrower than the body.
    for side in (1, -1):
        cutter = (cq.Workplane("YZ").polyline([(side * (WIDTH / 2 + 5), 1120), (side * (WIDTH / 2 + 5), HEIGHT + 50),
                                               (side * (WIDTH / 2 - 210), HEIGHT + 50)]).close()
                  .extrude(LENGTH / 2 + 10, both=True))
        shell = shell.cut(cutter)
    try:
        shell = shell.edges().fillet(45)
    except Exception:  # noqa: BLE001 - fillets are cosmetic; keep the sharp shell if OCCT refuses
        pass
    # Wheel arches
    for x in WHEEL_X:
        arch = cq.Workplane("XZ").center(x, WHEEL_R).circle(WHEEL_R + 60).extrude(WIDTH, both=True)
        shell = shell.cut(arch)
    return shell


def wheel() -> cq.Workplane:
    tyre = cq.Workplane("XZ").circle(WHEEL_R).circle(RIM_R).extrude(WHEEL_W / 2, both=True)
    rim = cq.Workplane("XZ").circle(RIM_R).extrude(WHEEL_W / 2 - 20, both=True)
    return tyre.union(rim)


def build() -> cq.Assembly:
    assy = cq.Assembly(name="sedan_shell")
    assy.add(body(), name="body", color=cq.Color(0.55, 0.65, 0.85, 0.35))
    for i, (x, y) in enumerate([(WHEEL_X[0], TRACK / 2), (WHEEL_X[0], -TRACK / 2), (WHEEL_X[1], TRACK / 2), (WHEEL_X[1], -TRACK / 2)]):
        assy.add(wheel(), name=f"wheel_{['fl', 'fr', 'rl', 'rr'][i]}", loc=cq.Location(cq.Vector(x, y, WHEEL_R)),
                 color=cq.Color(0.12, 0.12, 0.13, 1.0))
    return assy


def glb_bounds(path: Path) -> tuple[list[float], list[float]]:
    """Scene bounding box from the GLB accessor min/max (no glTF library needed)."""
    data = path.read_bytes()
    length = struct.unpack_from("<I", data, 12)[0]
    doc = json.loads(data[20:20 + length].decode("utf-8"))
    lo, hi = [float("inf")] * 3, [float("-inf")] * 3
    for acc in doc.get("accessors", []):
        if acc.get("type") == "VEC3" and "min" in acc and "max" in acc:
            lo = [min(a, b) for a, b in zip(lo, acc["min"])]
            hi = [max(a, b) for a, b in zip(hi, acc["max"])]
    return lo, hi


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / "sedan.glb"
    build().export(str(out), exportType="GLTF", tolerance=0.8, angularTolerance=0.3)   # coarser mesh: this is a context shell
    lo, hi = glb_bounds(out)
    size = [round(h - l, 3) for l, h in zip(lo, hi)]
    (OUT_DIR / "SOURCE.txt").write_text(
        "sedan.glb — generic sedan shell, procedurally generated by assets/build_car_shell.py (CadQuery / OCCT).\n"
        "Own asset, no third-party geometry; free to use in customer-facing material.\n"
        f"Modelled in mm ({LENGTH:.0f} × {WIDTH:.0f} × {HEIGHT:.0f} mm, wheelbase {WHEELBASE:.0f}); the glTF writer emits metres, Y-up.\n"
        f"GLB bounds (m): min={[round(v, 3) for v in lo]} max={[round(v, 3) for v in hi]} size={size}\n"
        "In a 1 unit = 1 mm three.js scene: gltf.scene.scale.setScalar(1000); road is y = 0; +X is the front (hood).\n"
        "Nodes: body (translucent shell), wheel_fl / wheel_fr / wheel_rl / wheel_rr.\n", encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB) bounds(m) min={lo} max={hi} size={size}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
